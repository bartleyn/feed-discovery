"""
feedmoreseemore — periodic full BERTopic re-carve of the explorer layout.

The liveness DAG grows the map incrementally (append_layout_incremental assigns each new
feed to its nearest EXISTING micro). That is cheap and preserves every label and hand
correction, but it can only ever sort feeds into clusters that were carved months ago — a
genuinely new topic gets absorbed into whatever is nearest instead of forming its own. This
DAG is the periodic correction for that drift: re-embed, re-cluster, re-label from scratch.

**It builds into a STAGING directory and deliberately does NOT promote.**

That is not caution for its own sake — a rebuild refits UMAP and HDBSCAN, so every cluster
id, label, and position changes. Consequences that need a human:

  - reparent_theme fixes are keyed to specific theme IDs that no longer mean the same thing
    after a re-carve, so they cannot be replayed mechanically and must be re-decided.
  - relabel_layout / any hand-edited labels are regenerated by the LLM and will differ.
  - The frontend's SUPER_COLORS / SUPER_SHORT arrays are indexed by super id; a rebuild that
    changes the super count needs a matching code change.
  - Cluster quality is a judgement call. Auto-promoting would let a bad re-carve silently
    replace a good curated map on a schedule.

So: this DAG produces `public/data_new` and stops. Review it by pointing the explorer at the
staging dir, then promote by hand once satisfied.

Rule-based curation IS replayed automatically, because it is derived from the feeds
themselves (keyword sets, creator-DID allow-lists, a declarative overrides file) rather than
from cluster ids, so it survives a re-carve intact.

Pipeline: rebuild -> likes -> identity -> firstparty -> trending -> overrides -> report.
"""
import os
import subprocess
from datetime import datetime, timedelta

from airflow.sdk import DAG, task

REPO = os.environ.get(
    "FEEDMORESEEMORE_DIR",
    "/Users/nathanbartley/srv/feedmoreseemore",
)
FEED_DISCOVERY = os.path.join(REPO, "feed-discovery")
FEED_EXPLORER = os.path.join(REPO, "feed-explorer")
PUBLIC =os.path.join(REPO, "feed-explorer", "public")
STAGING = os.path.join(PUBLIC, "data_new")
OVERRIDES = os.path.join(FEED_DISCOVERY, "cluster_overrides.json")

# Same pinned interpreter as the liveness DAG — numpy/psycopg2/anthropic/sentence-transformers
# live in the system Python's user site-packages, NOT Airflow's venv.
PYTHON = os.environ.get("FEEDMORESEEMORE_PYTHON", "/Library/Developer/CommandLineTools/usr/bin/python3")

default_args = {"retries": 0}  # a half-finished re-cluster should not silently retry


def py(module: str, *args: str) -> None:
    # Layout scripts live under feed-explorer/scripts.
    cmd = [PYTHON, "-W", "ignore", "-m", module, *args]
    r = subprocess.run(cmd, cwd=FEED_EXPLORER)
    if r.returncode != 0:
        raise RuntimeError(f"{' '.join(cmd)} exited {r.returncode}")


with DAG(
    "feedmoreseemore_layout_rebuild",
    description="Full BERTopic re-carve into public/data_new for review (never auto-promoted)",
    start_date=datetime(2026, 1, 1),
    schedule="0 3 1 * *",   # 3am on the 1st. Monthly: the incremental append keeps the map
                            # current day to day, so this only needs to catch topic drift.
    catchup=False,
    max_active_runs=1,
    default_args=default_args,
    tags=["feedmoreseemore", "layout", "manual-promote"],
) as dag:

    @task()
    def rebuild():
        # Re-embeds and re-clusters the whole live pool; the slow, expensive step
        # (UMAP + HDBSCAN + ~280 Haiku labeling calls).
        py("scripts.build_feed_layout_bertopic", "--out-dir", STAGING)

    @task()
    def likes():
        py("scripts.add_likes_to_layout", "--data", STAGING)

    @task()
    def identity():
        # Keyword/allow-list driven, so it re-derives correctly against new cluster ids.
        py("scripts.reassign_identity_feeds", "--data", STAGING)

    @task()
    def firstparty():
        py("scripts.reassign_firstparty_feeds", "--data", STAGING)

    @task()
    def trending():
        py("scripts.add_trending_super", "--data", STAGING)

    @task()
    def overrides():
        # Declarative and idempotent by design — the file names TARGET parents, so it is
        # replayable after a re-cluster. Skipped when no overrides have been exported from
        # the Tree view yet (none on disk as of 2026-08-09).
        if not os.path.isfile(OVERRIDES):
            print(f"no {OVERRIDES}; nothing to replay")
            return
        py("scripts.apply_overrides", "--data", STAGING, "--overrides", OVERRIDES)

    @task()
    def report():
        """Diff the staging carve against what's live so the review has numbers to start from."""
        import json

        def load(d):
            with open(os.path.join(d, "feeds_index.json")) as fh:
                return json.load(fh)

        new = load(STAGING)
        cur = load(os.path.join(PUBLIC, "data"))
        print(f"n:      {cur['n']:,} -> {new['n']:,}")
        for tier in ("supers", "themes", "micros"):
            print(f"{tier:<7} {len(cur[tier]):>4} -> {len(new[tier]):>4}")
        print("\nnew supers:")
        for s in new["supers"]:
            print(f"  {s['id']:>3}  {s['count']:>7,}  {s['label']}")
        if len(new["supers"]) != len(cur["supers"]):
            print("\n!! super COUNT changed — feed-explorer's SUPER_COLORS / SUPER_SHORT "
                  "arrays are indexed by super id and need a matching code change.")
        print(f"\nStaged at {STAGING}. NOT promoted — review, then swap into public/data "
              "by hand (keep a backup of the current data/).")

    rebuild() >> likes() >> identity() >> firstparty() >> trending() >> overrides() >> report()
